-- ShopFlow industry-aware platform foundation
alter table public.shopflow_profiles
  add column if not exists business_type text not null default 'general'
  check (business_type in ('general','restaurant','fashion','electronics','beauty','services'));

create table if not exists public.shopflow_products (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  description text not null default '',
  category text not null default '',
  price numeric(12,2) not null default 0 check (price >= 0),
  stock integer not null default 0 check (stock >= 0),
  image_url text not null default '',
  options jsonb not null default '{}'::jsonb,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists shopflow_products_user_idx on public.shopflow_products(user_id, created_at desc);

create table if not exists public.shopflow_customers (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  full_name text not null,
  email text not null default '',
  phone text not null default '',
  notes text not null default '',
  created_at timestamptz not null default now()
);
create index if not exists shopflow_customers_user_idx on public.shopflow_customers(user_id, created_at desc);

create table if not exists public.shopflow_orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  customer_id uuid references public.shopflow_customers(id) on delete set null,
  order_number bigint generated by default as identity,
  status text not null default 'new' check (status in ('new','confirmed','preparing','shipped','completed','cancelled')),
  total numeric(12,2) not null default 0 check (total >= 0),
  currency text not null default 'EGP',
  items jsonb not null default '[]'::jsonb,
  customer_snapshot jsonb not null default '{}'::jsonb,
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists shopflow_orders_user_idx on public.shopflow_orders(user_id, created_at desc);

create table if not exists public.shopflow_pages (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  slug text not null,
  template text not null default 'basic',
  content jsonb not null default '{}'::jsonb,
  is_published boolean not null default false,
  updated_at timestamptz not null default now(),
  unique(user_id, slug)
);

create table if not exists public.shopflow_integrations (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  provider text not null,
  display_name text not null,
  status text not null default 'not_connected' check (status in ('not_connected','pending','connected','error')),
  public_config jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  unique(user_id, provider)
);

create table if not exists public.shopflow_team_members (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete cascade,
  member_email text not null,
  role text not null default 'staff' check (role in ('manager','catalog','orders','support','staff')),
  invite_status text not null default 'pending' check (invite_status in ('pending','accepted','revoked')),
  created_at timestamptz not null default now(),
  unique(owner_id, member_email)
);

create table if not exists public.shopflow_appointments (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  customer_name text not null,
  service_name text not null,
  starts_at timestamptz not null,
  status text not null default 'booked' check (status in ('booked','confirmed','completed','cancelled')),
  notes text not null default '',
  created_at timestamptz not null default now()
);

